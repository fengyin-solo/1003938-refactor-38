/** 按人数与成绩清单生成报名名单：成绩缺省表示尚未考核，名单是参训人数与考核通过率的共同数据源。 */
function buildRoster(
  size: number,
  scores: Array<number | ''>,
  org: string,
  prefix: string,
): RosterMember[] {
  return Array.from({ length: size }, (_, index) => ({
    key: `${prefix}-${String(index + 1).padStart(2, '0')}`,
    姓名: `监测员${index + 1}`,
    单位: org,
    出勤: true,
    成绩: scores[index] ?? '',
  }))
}

